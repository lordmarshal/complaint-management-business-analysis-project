"""Load complaints_2024.csv into SQLite, run every query in analysis.sql,
and write the results to query_results.md.

Usage (from this folder):  python run_analysis.py
"""
import csv
import os
import re
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
conn = sqlite3.connect(":memory:")
with open(os.path.join(HERE, "complaints_2024.csv"), newline="") as f:
    rows = list(csv.reader(f))
cols = rows[0]
conn.execute(f"CREATE TABLE complaints ({', '.join(c + ' TEXT' for c in cols)})")
conn.executemany(f"INSERT INTO complaints VALUES ({', '.join('?' * len(cols))})", rows[1:])

sql = open(os.path.join(HERE, "analysis.sql")).read()
blocks = re.split(r"^-- @", sql, flags=re.M)[1:]
out = ["# Query Results", "", "Generated by `run_analysis.py` from `analysis.sql` and `complaints_2024.csv`.", ""]
for block in blocks:
    title, query = block.split("\n", 1)
    cur = conn.execute(query)
    names = [d[0] for d in cur.description]
    out += [f"## {title.strip()}", "", "| " + " | ".join(names) + " |", "|" + "---|" * len(names)]
    for r in cur.fetchall():
        out.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    out.append("")
open(os.path.join(HERE, "query_results.md"), "w").write("\n".join(out))
print("\n".join(out))
